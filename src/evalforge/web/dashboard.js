  document.querySelector('#source-preview').hidden = !profile?.can_preview_retrieval;
  document.querySelector('#model-setup').hidden = !profile?.model_settings;
  const retrievalOnly = profile?.can_preview_retrieval && !profile.uses_model;
  document.querySelector('.next-step').textContent = retrievalOnly ? '2. Evaluate retrieval: Run evaluation checks whether each question finds its labeled supporting document. No AI key is needed.' : '2. Evaluate AI answers: Complete the model setup below, then Run evaluation to generate and check model answers.';
