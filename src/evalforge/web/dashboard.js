async function loadJobs() {
  try {
    const data = await get('/api/jobs');
    const panel = document.querySelector('#job-history'); panel.replaceChildren();
    for (const job of data.jobs.slice(0,jobLimit)) {
      const item = node('article', undefined, 'job-entry');
      const label = {COMPLETED:'Finished',ERROR:'Could not complete',CANCELLED:'Stopped',CANCELLING:'Stopping',RUNNING:'Running',QUEUED:'Queued',INTERRUPTED:'Interrupted'}[job.status];
      item.append(node('strong', `${job.profile ?? 'Saved job'} · ${label}`),node('p', `${new Date(job.created_at).toLocaleString()} · ${job.message}`));
      if (job.comparison_status && job.status === 'COMPLETED') item.append(badge(job.comparison_status));
      if (job.baseline_name) item.append(node('p', `Approved reference: ${job.baseline_name}`));
      if (job.experiment_directory) { const open=node('button','View comparison'); open.addEventListener('click',async () => {await selectExperiment(job.experiment_directory); detail.scrollIntoView({behavior:'smooth'});}); item.append(open); }
      if (['QUEUED','RUNNING'].includes(job.status)) {const stop=node('button','Stop job');stop.addEventListener('click',()=>cancelJob(job.id));item.append(stop);}
      panel.append(item);
    }
    if (!data.jobs.length) panel.append(node('p','No browser jobs yet. Start an evaluation above.'));
    if (data.invalid_jobs) panel.append(node('p',`${data.invalid_jobs} unreadable job records were skipped.`));
    document.querySelector('#more-jobs').hidden = data.jobs.length <= jobLimit;
  } catch (error) {document.querySelector('#job-history').textContent = error.message;}
}
document.querySelector('#refresh-jobs').addEventListener('click',loadJobs);
document.querySelector('#more-jobs').addEventListener('click',()=>{jobLimit+=10;loadJobs();});
